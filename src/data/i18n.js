let currentLanguage = 'en';

export function getLanguage() {
  return currentLanguage;
}

export function setLanguage(lang) {
  if (I18N_DATA[lang]) {
    currentLanguage = lang;
    try {
      if (typeof localStorage !== 'undefined') {
        localStorage.setItem('sunstarved_lang', lang);
      }
    } catch (e) {
      // Ignore storage errors in restricted contexts
    }
    return true;
  }
  return false;
}

export function t(key, fallback = '') {
  const dict = I18N_DATA[currentLanguage] || I18N_DATA.en;
  return dict[key] || I18N_DATA.en[key] || fallback || key;
}

export function initI18n() {
  try {
    if (typeof localStorage !== 'undefined') {
      const saved = localStorage.getItem('sunstarved_lang');
      if (saved && I18N_DATA[saved]) {
        currentLanguage = saved;
      }
    }
  } catch (e) {
    // Ignore storage errors
  }
  return currentLanguage;
}
