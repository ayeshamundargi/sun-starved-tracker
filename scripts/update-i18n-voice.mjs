const filePath = path.resolve('src/data/i18n.js');
let content = fs.readFileSync(filePath, 'utf8');

// For each language, find where its block ends and inject the new keys before the closing brace
const langs = ['en', 'hi', 'kn', 'ta', 'te', 'mr'];

langs.forEach((lang, index) => {
  const keys = voiceKeys[lang];
  const keysCode = Object.entries(keys)
    .map(([k, v]) => `    ${k}: ${JSON.stringify(v)},`)
    .join('\n');

  // Search for the end of this language's dictionary
  // If not the last language, look for `  },\n\n  ${nextLang}:`
  // If the last language, look for `  }\n};`
  if (index < langs.length - 1) {
    const nextLang = langs[index + 1];
    const targetPattern = new RegExp(`(\\n  \\},\\n\\n  ${nextLang}: \\{)`);
    if (targetPattern.test(content)) {
      content = content.replace(targetPattern, `\n\n    // Multilingual AI Voice Assistant & Voice Alerts\n${keysCode}\n  },\n\n  ${nextLang}: {`);
      console.log(`Successfully injected voice keys into [${lang}]`);
    } else {
      console.error(`Could not match pattern for [${lang}]`);
    }
  } else {
    const targetPattern = /(\n  \}\n\};\n)/;
    if (targetPattern.test(content)) {
      content = content.replace(targetPattern, `\n\n    // Multilingual AI Voice Assistant & Voice Alerts\n${keysCode}\n  }\n};\n`);
      console.log(`Successfully injected voice keys into [${lang}]`);
    } else {
      console.error(`Could not match pattern for last lang [${lang}]`);
    }
  }
});

fs.writeFileSync(filePath, content, 'utf8');
console.log('Finished updating src/data/i18n.js');
